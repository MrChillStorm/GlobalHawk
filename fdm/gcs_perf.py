#!/usr/bin/env python3
"""The performance table the ground control station forecasts with, sampled from the JSBSim model.

    python3 fdm/gcs_perf.py        about a minute; writes GlobalHawk/gcs/js/perfdata.js

For each height and weight, on the speed schedule (fdm/mission.py), standard atmosphere, no wind:
    climb    at maximum thrust: rate (ft/min, with the correction for speed rising with height), fuel flow (lb/h)
    level    fuel flow (lb/h); null where the aircraft cannot hold height there
    descent  at idle with half spoilers, as the mission manager descends: rate (ft/min, negative), fuel flow
and the true airspeed (kt) of the schedule at each height.

And the landing, for each weight at two field heights: the flight model's own approach and landing (as
fdm/phase7b_checks.py flies them), how far past the aiming point it touches down and how far past it is down to 15 kt,
where the rollout ends and the taxi begins. No wind, a level dry runway.
"""
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import harness as H         # noqa: E402
import mission as M         # noqa: E402

ALT = [2500.0, 5000.0, 10000.0, 15000.0, 20000.0, 25000.0, 30000.0, 35000.0, 40000.0, 45000.0, 50000.0, 55000.0, 60000.0, 65000.0]
WEIGHT = [11500.0, 15000.0, 19000.0, 23000.0, 26700.0]
LAND_ELEV = [0.0, 5000.0]


def landing_roll(f, weight, elev):
    """An approach from 5 nmi and the landing under the laws: (touchdown, down to 15 kt), ft past the aiming point."""
    import math
    import missionmgr as MM
    import phase7b_checks as C
    fld = MM.Field(35.0, -117.0, elev)
    u = C.unit(C.COURSE)
    aim, far, d0 = fld.ll(0, 0), fld.ll(*(-8 * C.NM * u)), 5 * C.NM
    first = fld.ll(*(-d0 * u))
    keas = math.sqrt(weight / (0.645 * 540 * 0.5 * 0.0023769)) / H.KT
    t = H.trim(f, alt=elev + 5.3 + d0 * 0.07782, kcas=keas, weight=weight, gamma=-4.45, gear=1.0, spoiler=2 / 3, lat=first[0], lon=first[1],
               psi=C.COURSE, terrain=elev)
    H.engage(f, t, pitch_mode=1, roll_mode=2, ground_steer=1, land_mode=1, rwy_elev_ft=elev, leg_lat0_deg=far[0], leg_lon0_deg=far[1],
             leg_lat1_deg=aim[0], leg_lon1_deg=aim[1])
    log = H.run(f, 300, every=6)
    if not (log['mains'] > 0).any():
        raise ValueError('no touchdown at %.0f lb, %.0f ft' % (weight, elev))
    down = int(np.argmax(log['mains'] > 0))
    under = log['vg'][down:] < 15.0
    if not under.any():
        raise ValueError('not under 15 kt at %.0f lb, %.0f ft' % (weight, elev))
    return float(-log['togo'][down]), float(-log['togo'][down + int(np.argmax(under))])


def main():
    f = H.load()
    t = dict(alt_ft=ALT, weight_lb=WEIGHT, ktas=[round(M.true_airspeed(a) / H.KT, 1) for a in ALT],
             climb_fpm=[], climb_pph=[], level_pph=[], descent_fpm=[], descent_pph=[])
    for a in ALT:
        rows = {k: [] for k in ('climb_fpm', 'climb_pph', 'level_pph', 'descent_fpm', 'descent_pph')}
        for w in WEIGHT:
            roc, flow, _ = M.point(f, a, w)
            rows['climb_fpm'].append(round(float(roc), 1))
            rows['climb_pph'].append(round(float(flow), 1))
            lv = H.trim(f, alt=a, weight=w, **M.schedule(a))
            rows['level_pph'].append(round(lv['fuel_flow'], 1) if lv['ok'] and lv['throttle'] < 0.999 else None)
            d = H.trim(f, alt=a, weight=w, throttle=0.0, spoiler=0.5, **M.schedule(a))
            rows['descent_fpm'].append(round(float(d['ktas'] * H.KT * np.sin(np.radians(d['cond']['gamma'])) * 60.0), 1))
            rows['descent_pph'].append(round(d['fuel_flow'], 1))
        for k in rows:
            t[k].append(rows[k])
        print('%6.0f ft: climb %s ft/min, level %s lb/h, descent %s ft/min' % (a, rows['climb_fpm'], rows['level_pph'], rows['descent_fpm']), flush=True)
    t['landing'] = dict(weight_lb=WEIGHT, elev_ft=LAND_ELEV, touchdown_ft=[], slow_ft=[])
    for e in LAND_ELEV:
        rolls = [landing_roll(f, w, e) for w in WEIGHT]
        t['landing']['touchdown_ft'].append([round(r[0]) for r in rolls])
        t['landing']['slow_ft'].append([round(r[1]) for r in rolls])
        print('landing at %4.0f ft: touchdown %s ft past the aiming point, down to 15 kt %s ft past it' % (e, t['landing']['touchdown_ft'][-1], t['landing']['slow_ft'][-1]), flush=True)
    out = os.path.join(HERE, '..', 'GlobalHawk', 'gcs', 'js', 'perfdata.js')
    with open(out, 'w') as fh:
        fh.write('/** Generated by fdm/gcs_perf.py from the JSBSim model: do not edit. Rows are heights, columns weights. */\n'
                 "(function (root) {\n  'use strict';\n  const data = %s;\n"
                 "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n  else (root.GCS = root.GCS || {}).perfdata = data;\n"
                 "})(typeof window !== 'undefined' ? window : globalThis);\n" % json.dumps(t))
    print('wrote', os.path.relpath(out))


if __name__ == '__main__':
    main()
