#!/usr/bin/env python3
"""One SU2 case of the LRN 1015: python3 fdm/cfd/run_case.py MACH REYNOLDS ALPHA [--restart-from CASE] [--iter N]

RANS with Spalart-Allmaras, fully turbulent, adiabatic wall, chord 1, moments about the quarter chord, the mesh of mesh_lrn1015.py. The
case's directory is tools/su2-runs/<name>/ (outside the repository's tracked files); its result, the lift, drag and moment coefficients
(the means over the last 200 iterations, with their spread) and the final density residual, is written there as result.json.
SU2's moment about z is positive nose-DOWN for flow along +x (counter-clockwise lifts the tail), so the result's cm is its negative: nose-up positive,
like the tunnel's.
"""
import json
import os
import shutil
import subprocess
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..', '..')
SU2 = os.path.join(ROOT, 'tools', 'su2', 'bin', 'SU2_CFD')
RUNS = os.path.join(ROOT, 'tools', 'su2-runs')
MESH = os.path.join(RUNS, 'lrn1015.su2')

CFG = """% LRN 1015, Mach {mach}, Reynolds {re:g}, {alpha} deg: generated by fdm/cfd/run_case.py
SOLVER= RANS
KIND_TURB_MODEL= SA
MATH_PROBLEM= DIRECT
RESTART_SOL= {restart}
MACH_NUMBER= {mach}
AOA= {alpha}
SIDESLIP_ANGLE= 0.0
FREESTREAM_TEMPERATURE= 288.15
REYNOLDS_NUMBER= {re:g}
REYNOLDS_LENGTH= 1.0
REF_ORIGIN_MOMENT_X= 0.25
REF_ORIGIN_MOMENT_Y= 0.0
REF_ORIGIN_MOMENT_Z= 0.0
REF_LENGTH= 1.0
REF_AREA= 1.0
MARKER_HEATFLUX= ( airfoil, 0.0 )
MARKER_FAR= ( farfield )
MARKER_PLOTTING= ( airfoil )
MARKER_MONITORING= ( airfoil )
NUM_METHOD_GRAD= WEIGHTED_LEAST_SQUARES
CFL_NUMBER= {cfl}
CFL_ADAPT= YES
CFL_ADAPT_PARAM= ( 0.5, 1.2, 1.0, {cflmax} )
CONV_NUM_METHOD_FLOW= ROE
MUSCL_FLOW= YES
SLOPE_LIMITER_FLOW= VENKATAKRISHNAN
VENKAT_LIMITER_COEFF= 0.05
CONV_NUM_METHOD_TURB= BOUNDED_SCALAR
MUSCL_TURB= NO
TIME_DISCRE_FLOW= EULER_IMPLICIT
TIME_DISCRE_TURB= EULER_IMPLICIT
LINEAR_SOLVER= FGMRES
LINEAR_SOLVER_PREC= ILU
LINEAR_SOLVER_ERROR= 1e-6
LINEAR_SOLVER_ITER= 10
ITER= {iters}
CONV_FIELD= RMS_DENSITY
CONV_RESIDUAL_MINVAL= -9
CONV_STARTITER= 10
MESH_FILENAME= lrn1015.su2
MESH_FORMAT= SU2
SOLUTION_FILENAME= solution.dat
RESTART_FILENAME= restart.dat
CONV_FILENAME= history
OUTPUT_FILES= ( RESTART, SURFACE_CSV )
OUTPUT_WRT_FREQ= 500
HISTORY_OUTPUT= ( ITER, RMS_RES, AERO_COEFF )
SCREEN_OUTPUT= ( INNER_ITER, RMS_DENSITY, LIFT, DRAG, MOMENT_Z )
"""


def name(mach, re, alpha):
    return 'M%.2f_Re%g_a%.1f' % (mach, re / 1e6, alpha)


def run(mach, re, alpha, restart_from=None, iters=6000, cfl=5.0, cflmax=100.0):
    case = os.path.join(RUNS, name(mach, re, alpha))
    os.makedirs(case, exist_ok=True)
    shutil.copy(MESH, os.path.join(case, 'lrn1015.su2'))
    restart = 'NO'
    if restart_from:
        src = os.path.join(RUNS, restart_from, 'restart.dat')
        if os.path.exists(src):
            shutil.copy(src, os.path.join(case, 'solution.dat'))
            restart = 'YES'
    open(os.path.join(case, 'case.cfg'), 'w').write(CFG.format(mach=mach, re=re, alpha=alpha, restart=restart, iters=iters, cfl=cfl, cflmax=cflmax))
    log = open(os.path.join(case, 'su2.log'), 'w')
    subprocess.run([SU2, 'case.cfg'], cwd=case, stdout=log, stderr=subprocess.STDOUT)
    log.close()
    return result(case, mach, re, alpha)


def result(case, mach, re, alpha):
    hist = os.path.join(case, 'history.csv')
    if not os.path.exists(hist):
        return None
    head = open(hist).readline().replace('"', '').strip().split(',')
    head = [h.strip() for h in head]
    a = np.loadtxt(hist, delimiter=',', skiprows=1, ndmin=2)
    col = lambda n: a[:, head.index(n)]
    cl, cd, cm = col('CL'), col('CD'), col('CMz')
    k = slice(max(0, len(cl) - 200), None)
    out = dict(mach=mach, re=re, alpha=alpha, iterations=int(len(cl)), cl=float(np.mean(cl[k])), cl_spread=float(np.ptp(cl[k])), cd=float(np.mean(cd[k])),
               cm=float(-np.mean(cm[k])), res_rho=float(col('rms[Rho]')[-1]), finite=bool(np.all(np.isfinite(a[-1]))))
    json.dump(out, open(os.path.join(case, 'result.json'), 'w'))
    return out


if __name__ == '__main__':
    args = [x for x in sys.argv[1:] if not x.startswith('--')]
    mach, re, alpha = float(args[0]), float(args[1]), float(args[2])
    rf = sys.argv[sys.argv.index('--restart-from') + 1] if '--restart-from' in sys.argv else None
    it = int(sys.argv[sys.argv.index('--iter') + 1]) if '--iter' in sys.argv else 6000
    print(run(mach, re, alpha, rf, it))
